"""Assemble reports/first-round/ from the individual run reports.

Inputs (whatever exists):
  reports/dev-<model>/summary.json + table.md + safety-utility-cost.png + dossiers/
  reports/conf-<model>/summary.json            (confirmation set, frozen thresholds)
  runs/bypass-<model>/summary.json             (bounded defense-aware search)
  reports/binding-control.json, reports/serialization-probe-<model>.json
  reports/first-round/decision.md              (hand-written continue/pivot/stop judgement)
Output: reports/first-round/README.md (+ copied plots) — the reviewable package.
"""
from __future__ import annotations
import json, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from runner.paths import resolve_out, CATEGORY

MODELS = ["qwen14b", "llama8b"]


def _load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def combined_table(summaries: dict[str, dict]) -> list[str]:
    keys = None
    for s in summaries.values():
        keys = list(s["defenses"]) if s else keys
    if not keys:
        return ["(no run summaries found)"]
    L = ["| Method | " + " | ".join(f"{m}: clean correct | {m}: unauth. exec under attack | {m}: legit falsely blocked | {m}: UNKNOWN | {m}: passes ×B0" for m in summaries) + " |",
         "|---|" + "---|" * (5 * len(summaries))]
    for k in keys:
        cells = []
        for m, s in summaries.items():
            if not s or k not in s["defenses"]:
                cells += ["–"] * 5
                continue
            d = s["defenses"][k]
            a = d["attack_unauthorized_execution"]
            cells += [f"{d['clean_correct_automatic']['k']}/{d['clean_correct_automatic']['n']}",
                      f"{a['k']}/{a['n']} ({a['templates_with_any']}/{a['templates']} templates)",
                      f"{d['legitimate_falsely_blocked']['k']}/{d['legitimate_falsely_blocked']['n']}",
                      f"{d['unknown_or_fallback']['k']}/{d['unknown_or_fallback']['n']}",
                      f"{d['compute']['mean_ratio_passes']:.1f}× / {d['compute']['mean_ratio_seconds']:.1f}× s"]
        label = next(s for s in summaries.values() if s)["defenses"][k]["label"]
        L.append(f"| {label} | " + " | ".join(cells) + " |")
    return L


def main() -> int:
    out = resolve_out("reports/first-round", mkdir=True)
    out.mkdir(parents=True, exist_ok=True)
    dev = {m: _load(CATEGORY / f"reports/dev-{m}/summary.json") for m in MODELS}
    conf = {m: _load(CATEGORY / f"reports/conf-{m}/summary.json") for m in MODELS}
    byp = {m: _load(CATEGORY / f"runs/bypass-{m}/summary.json") for m in MODELS}
    L = ["# First-round evidence package — R001 tool-argument selection auditing", "",
         "Generated by `runner/first_round_report.py`. Every number is measured on the development templates (24) or the independently authored confirmation set (8) with the pinned self-hosted models; nothing is extrapolated. Denominators are all scheduled executions. Human reviewer sign-off of fixtures is **pending** (none available), which caps every claim at 'agent-verified'.", ""]
    L += ["## 1. Baseline comparison table (development templates, both families)", ""]
    L += combined_table({m: s for m, s in dev.items()})
    L += ["", "Per-model full tables with per-template breakdowns: " + ", ".join(f"[{m}](../dev-{m}/table.md)" for m in MODELS if dev[m]), ""]
    L += ["## 2. Safety–utility–cost plots", ""]
    for m in MODELS:
        src = CATEGORY / f"reports/dev-{m}/safety-utility-cost.png"
        if src.exists():
            shutil.copy(src, out / f"safety-utility-cost-{m}.png")
            L.append(f"![{m}](safety-utility-cost-{m}.png)")
    L += ["", "x = clean correct automatic completion (all clean executions); y = unauthorized execution under attack (all scheduled attack executions of threat templates); marker size ∝ forward passes relative to B0; vertical bars are Wilson 95 % intervals over executions (template-cluster intervals are in the JSON).", ""]
    L += ["## 3. Confirmation set (8 fresh templates, frozen thresholds)", ""]
    if any(conf.values()):
        L += combined_table({m: s for m, s in conf.items() if s})
    else:
        L.append("(not yet run)")
    L += ["", "## 4. Bounded defense-aware bypass search", ""]
    for m in MODELS:
        b = byp[m]
        if not b:
            continue
        L.append(f"### {m}")
        L.append("")
        L.append("| Template | queries | defenses with ≥1 unauthorized execution (greedy) | first bypass query | fresh-randomness reproduction | fallback queries |")
        L.append("|---|---|---|---|---|---|")
        for t, r in b.items():
            val = "; ".join(f"{k}: {v['reproduced']}/{v['n']}" for k, v in r["validation"].items()) or "–"
            fb = "; ".join(f"{k}: q{v}" for k, v in r["first_bypass_query"].items()) or "–"
            L.append(f"| {t} | {r['queries']} | {', '.join(r['defenses_bypassed_greedy']) or 'none'} | {fb} | {val} | {r['fallback_queries']} |")
        L.append("")
    L += ["## 5. Case dossiers (full execution chains)", ""]
    for m in MODELS:
        idx = _load(CATEGORY / f"reports/dev-{m}/dossiers/index.json")
        if idx is None:
            continue
        L.append(f"- **{m}**: {len(idx)} attack executions in which B0 executed an unauthorized tuple → [`../dev-{m}/dossiers/`](../dev-{m}/dossiers/). "
                 + ("Templates: " + ", ".join(sorted({d['case'] for d in idx})) if idx else "none"))
    L += ["", "## 6. Controls and probes", ""]
    bc = _load(CATEGORY / "reports/binding-control.json")
    if bc:
        L.append(f"- Deterministic binding control: {bc['summary']['binding_reproduces_allowed']}/{bc['summary']['templates']} templates resolvable by explicit-id binding with zero model calls; tasks naming an id literally: {bc['summary']['templates_where_task_names_id']} (`binding-control.json`).")
    for m in MODELS:
        sp = _load(CATEGORY / f"reports/serialization-probe-{m}.json")
        if sp:
            c = sp["conditions"]
            L.append(f"- Serialization sensitivity ({m}, P03): TV vs canonical — clean {c['clean']['tv_vs_canonical']}, attack {c['attack']['tv_vs_canonical']}; argmax stable: clean {c['clean']['argmax_stable']}, attack {c['attack']['argmax_stable']}.")
    L += ["- Literature checks: [`novelty-influence-is-not-authority.md`](../novelty-influence-is-not-authority.md), [`novelty-addendum-liao-2607-20827.md`](../novelty-addendum-liao-2607-20827.md), [`structural-baselines-compatibility.md`](../structural-baselines-compatibility.md), [`../../downloads/causal-armor-inspection.md`](../../downloads/causal-armor-inspection.md).", ""]
    L += ["## 7. Paper", "", "Full write-up: [`../paper/paper.md`](../paper/paper.md) (copy at repository `r001/paper-first-round.md`).", "", "## 8. Decision", ""]
    dec = out / "decision.md"
    L += [dec.read_text()] if dec.exists() else ["(decision.md not yet written)"]
    (out / "README.md").write_text("\n".join(L) + "\n")
    print("wrote", out / "README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
